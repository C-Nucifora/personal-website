import { chromium, devices } from "playwright";
import { mkdirSync, writeFileSync } from "node:fs";

const base = process.env.BASE || "http://127.0.0.1:4318";
if (new URL(base).hostname !== "127.0.0.1") throw new Error("Publication checks require an explicit loopback server");
const evidence = process.env.EVIDENCE || "/tmp/portfolio-publication";
mkdirSync(evidence, { recursive: true, mode: 0o700 });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const results = [];
const check = (name, pass, detail = "") => results.push({ name, pass: Boolean(pass), detail });
const page = await browser.newPage({ reducedMotion: "reduce" });
page.setDefaultTimeout(15000);
const errors = [];
const failures = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
page.on("response", (response) => { if (response.status() >= 400 && !response.url().includes("missing-route")) failures.push(`${response.status()} ${response.url()}`); });
try {
  for (const [width, height] of [[320,568], [568,320], [320,256], [768,1024], [1440,900], [2560,1440]]) {
    await page.setViewportSize({ width, height });
    for (const route of ["", "about/", "projects/", "resume/", "contact/", "help/"]) {
      await page.goto(`${base}/${route}`);
      await page.waitForSelector('html[data-js-ready="true"]');
      check(`${width}x${height} ${route || "home"} body fits`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      check(`${width}x${height} ${route || "home"} plain button reachable`, await page.getByRole("button", { name: "Switch to plain view", exact: true }).isVisible());
      if (route === "contact/") {
        check(`${width} direct contact shows contact content immediately`, await page.locator('[data-window="contact"] section[aria-label="Contact"]').evaluate((element) => {
          const pane = element.closest('[data-pane-scroll]').getBoundingClientRect();
          const rect = element.getBoundingClientRect();
          return rect.top >= pane.top - 2 && rect.top < pane.bottom;
        }));
      }
      if ([320,1440].includes(width)) await page.screenshot({ path: `${evidence}/${width}x${height}-${route.replace("/", "") || "home"}.png` });
    }
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base);
  await page.waitForSelector('html[data-js-ready="true"]');
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Terminal command input");
  check("desktop landing focuses the prompt", await page.getByRole("textbox", { name: "Terminal command input" }).evaluate((element) => element === document.activeElement));
  const cold = await browser.newPage({ reducedMotion: "reduce" });
  await cold.goto(base); await cold.waitForSelector('html[data-js-ready="true"]');
  await cold.waitForLoadState("networkidle");
  const initialResources = await cold.evaluate(() => performance.getEntriesByType("resource").map((entry) => ({ name: entry.name, bytes: entry.transferSize, duration: entry.duration })));
  writeFileSync(`${evidence}/initial-resources.json`, JSON.stringify(initialResources, null, 2));
  await cold.close();
  for (const key of ["ArrowUp", "ArrowUp", "ArrowDown", "ArrowDown", "ArrowLeft", "ArrowRight", "ArrowLeft", "ArrowRight", "b", "a"]) await page.keyboard.press(key);
  await page.waitForFunction(() => document.documentElement.dataset.theme === "crt");
  check("existing Konami sequence unlocks CRT", await page.getByRole("combobox", { name: "Theme" }).locator('option[value="crt"]').count() === 1);
  const themeIds = await page.getByRole("combobox", { name: "Theme" }).locator("option").evaluateAll((options) => options.map((option) => option.value));
  for (const theme of themeIds) {
    await page.getByRole("combobox", { name: "Theme" }).selectOption(theme);
    await page.waitForFunction((id) => document.documentElement.dataset.theme === id, theme);
    check(`${theme} selected through command layer`, await page.locator('[data-window="lobby"]').textContent().then((text) => text.includes(`theme ${theme}`)));
    await page.screenshot({ path: `${evidence}/theme-${theme}.png` });
  }
  const prompt = page.getByRole("textbox", { name: "Terminal command input", exact: true });
  await prompt.fill(""); await prompt.focus(); await prompt.press("Shift+Tab");
  check("Shift Tab exits prompt", !(await prompt.evaluate((element) => element === document.activeElement)));
  await prompt.fill("pw"); await prompt.press("Tab");
  check("nonempty Tab completes", await prompt.inputValue() === "pwd ");
  await prompt.fill(""); await prompt.press("Tab");
  check("empty Tab exits prompt", !(await prompt.evaluate((element) => element === document.activeElement)));
  await page.goto(`${base}/projects/`);
  await page.waitForSelector('html[data-js-ready="true"]');
  const projectInput = page.locator('[data-window="projects"] input');
  await page.waitForLoadState("networkidle");
  await projectInput.fill("vim ~/projects/terminal-portfolio/src/lib/vim/machine.ts");
  await projectInput.press("Enter");
  await page.waitForSelector('[data-window="projects"] .cm-editor');
  check("editor stays inside the terminal", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole("combobox", { name: "Theme" }).focus();
  await page.getByRole("combobox", { name: "Theme" }).selectOption("tokyo-night");
  check("theme dropdown retains native focus", await page.getByRole("combobox", { name: "Theme" }).evaluate((element) => element === document.activeElement));
  await page.getByRole("navigation", { name: "Sections", exact: true }).getByRole("button", { name: "1:about", exact: true }).click();
  await page.getByRole("navigation", { name: "Sections", exact: true }).getByRole("button", { name: "2:projects", exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.classList.contains("cm-content"));
  check("tab navigation restores Vim focus", await page.locator('.cm-content').evaluate((element) => element === document.activeElement));
  await page.keyboard.press("Control+b"); await page.keyboard.press("1");
  await page.keyboard.press("Control+b"); await page.keyboard.press("2");
  await page.waitForFunction(() => document.activeElement?.classList.contains("cm-content"));
  check("tmux window navigation restores Vim focus", await page.locator('.cm-content').evaluate((element) => element === document.activeElement));
  await page.keyboard.press("Control+b"); await page.keyboard.press("%");
  await page.keyboard.press("Control+b"); await page.keyboard.press("o");
  await page.waitForFunction(() => document.activeElement?.classList.contains("cm-content"));
  check("tmux pane navigation restores Vim focus", await page.locator('.cm-content').evaluate((element) => element === document.activeElement));
  await page.keyboard.press("Control+b"); await page.keyboard.press("o");
  await page.keyboard.press("Control+b"); await page.keyboard.press("x"); await page.keyboard.press("y");
  await page.waitForFunction(() => document.activeElement?.classList.contains("cm-content"));
  check("closing another pane restores Vim focus", await page.locator('.cm-content').evaluate((element) => element === document.activeElement));
  await page.keyboard.press("Escape"); await page.keyboard.type(":q"); await page.keyboard.press("Enter");
  await page.waitForSelector('[data-window="projects"] .cm-editor', { state: "detached" });
  await projectInput.focus();
  await page.keyboard.press("Control+b"); await page.keyboard.down("Shift"); await page.keyboard.press("%"); await page.keyboard.up("Shift");
  check("real shifted tmux split creates a second pane", await page.locator('[data-window="projects"] [data-pane-scroll]').count() === 2);
  await page.keyboard.press("Control+b"); await page.keyboard.press("x"); await page.keyboard.press("y");
  check("split closes through keyboard confirmation", await page.locator('[data-window="projects"] [data-pane-scroll]').count() === 1);
  await projectInput.focus();
  await page.keyboard.press("Control+b"); await page.keyboard.press("w");
  await page.getByRole("dialog", { name: "Window picker" }).getByRole("button").first().focus();
  await page.keyboard.press("Escape");
  check("Escape closes a picker with a focused button", await page.getByRole("dialog", { name: "Window picker" }).count() === 0);
  await projectInput.fill("cd terminal-portfolio/src/lib"); await projectInput.press("Enter");
  await page.getByRole("navigation", { name: "Sections", exact: true }).getByRole("button", { name: "3:resume", exact: true }).click();
  await page.locator('[data-status-bar] button', { hasText: "2:projects" }).click();
  check("status restores saved cwd", await page.locator('[data-title-bar] p').textContent().then((text) => text.includes("terminal-portfolio/src/lib")));
  await page.setViewportSize({ width: 320, height: 568 });
  check("deep cwd leaves a usable phone prompt", await projectInput.evaluate((element) => element.clientWidth >= 64));
  check("deep cwd phone body fits", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await projectInput.fill("open https://github.com/C-Nucifora"); await projectInput.press("Enter");
  check("phone confirmation fits", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  check("confirm has clickable cancel", await page.getByRole("button", { name: "Cancel", exact: true }).isVisible());
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.goto(`${base}/help/`); await page.waitForSelector('html[data-js-ready="true"]');
  await page.getByRole("button", { name: "Help", exact: true }).click();
  check("commands after long output scroll into view", await page.locator('[data-window="help"] [data-entry-id].scroll-mt-2').last().evaluate((element) => {
    const pane = element.closest('[data-pane-scroll]').getBoundingClientRect();
    const rect = element.getBoundingClientRect();
    return rect.top >= pane.top - 2 && rect.top < pane.bottom;
  }));
  await page.goto(`${base}/contact/?plain=1`);
  await page.waitForSelector('html[data-view="plain"]');
  check("plain contact route starts with contact", await page.locator('.static-fallback section[id]').first().getAttribute("id") === "contact");
  check("plain help and tools exist", await page.locator('#help').isVisible() && await page.locator('#about').textContent().then((text) => text.includes("Tools")));
  await page.getByRole("button", { name: "Back to the terminal" }).click();
  await page.reload();
  await page.waitForSelector('html[data-js-ready="true"]');
  check("return from forced plain survives refresh", await page.locator('html').getAttribute("data-view") !== "plain");
  await page.goto(base); await page.waitForSelector('html[data-js-ready="true"]');
  await page.getByRole("navigation", { name: "Sections", exact: true }).getByRole("button", { name: "3:resume", exact: true }).click();
  await page.getByRole("button", { name: "Switch to plain view", exact: true }).click();
  check("plain switching keeps the current section in view", await page.locator('.static-fallback #resume').evaluate((element) => Math.abs(element.getBoundingClientRect().top) < 5));
  await page.goto(`${base}/?plain=1`); await page.waitForSelector('html[data-view="plain"]');
  await page.evaluate(() => { document.body.style.zoom = "2"; });
  check("plain view fits at 200 percent CSS zoom", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const mobile = await browser.newContext({ ...devices["iPhone SE"], reducedMotion: "reduce" });
  const phone = await mobile.newPage();
  await phone.goto(base); await phone.waitForSelector('html[data-js-ready="true"]');
  check("touch landing does not open the keyboard automatically", await phone.evaluate(() => document.activeElement?.tagName !== "INPUT"));
  await phone.getByRole("textbox", { name: "Terminal command input" }).tap();
  check("touch prompt accepts explicit focus", await phone.evaluate(() => document.activeElement?.tagName === "INPUT"));
  await phone.screenshot({ path: `${evidence}/touch-prompt.png` });
  await mobile.close();
  const nojs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 320, height: 568 } });
  const fallback = await nojs.newPage();
  for (const route of ["about", "projects", "resume", "contact", "help"]) {
    await fallback.goto(`${base}/${route}/`);
    check(`no JS ${route} route starts at relevant section`, await fallback.locator('section[id]').first().getAttribute("id") === route);
    check(`no JS ${route} has navigation and mail`, await fallback.getByRole("navigation", { name: "Plain view sections" }).isVisible() && await fallback.locator('a[href="mailto:cgnucifora@proton.me"]').count() > 0);
    check(`no JS ${route} fits phone`, await fallback.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check(`no JS ${route} hides the inactive print button`, !(await fallback.getByRole("button", { name: "Print / Save as PDF" }).isVisible()));
  }
  await fallback.screenshot({ path: `${evidence}/nojs-help.png`, fullPage: true });
  await nojs.close();
  const sourceContext = await browser.newContext({ reducedMotion: "reduce" });
  const sourcePage = await sourceContext.newPage();
  await sourcePage.goto(base); await sourcePage.waitForSelector('html[data-js-ready="true"]');
  const sourcePrompt = sourcePage.getByRole("textbox", { name: "Terminal command input" });
  await sourcePrompt.fill("cat ~/projects/m1-core/Cargo.toml"); await sourcePrompt.press("Enter");
  await sourcePage.locator('[data-window="lobby"]').getByText("[package]", { exact: false }).first().waitFor();
  check("absolute public source works before visiting Projects", await sourcePage.locator('[data-window="lobby"]').isVisible());
  await sourceContext.close();
  check("no browser runtime or console errors", errors.length === 0, errors.join("\n"));
  check("no failed resource responses", failures.length === 0, failures.join("\n"));
} finally { await browser.close(); }
writeFileSync(`${evidence}/results.json`, JSON.stringify(results, null, 2));
for (const result of results) console.log(`${result.pass ? "PASS" : "FAIL"} ${result.name}${result.detail ? ` ${result.detail}` : ""}`);
console.log(`${results.filter((result) => result.pass).length}/${results.length} passed`);
if (results.some((result) => !result.pass)) process.exitCode = 1;
