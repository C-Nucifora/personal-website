/**
 * Bundles data/blog/*.md (frontmatter: title, date) into
 * data/generated/blog.ts, newest first. Zero posts is a valid state —
 * the blog window stays dormant (spec 2026-06-12). README.md is the
 * directory's documentation, never a post. Malformed files are skipped
 * with a warning, never a build failure.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** Parse one post file; returns null when frontmatter is unusable. */
export function parsePost(filename, text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  if (!m) return null;
  const fields = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^(\w+)\s*:\s*(.+)$/.exec(line.trim());
    if (kv) fields[kv[1].toLowerCase()] = kv[2].trim();
  }
  if (!fields.title || !fields.date) return null;
  return {
    slug: filename.replace(/\.md$/, ""),
    title: fields.title,
    date: fields.date,
    body: m[2].trim(),
  };
}

function main() {
  // Lazy: import.meta.url is only a real file:// URL when run by node,
  // and tests import parsePost without ever calling main().
  const root = fileURLToPath(new URL("..", import.meta.url));
  let files = [];
  try {
    files = readdirSync(`${root}data/blog`).filter(
      (f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md",
    );
  } catch {
    /* no data/blog directory yet — zero posts */
  }

  const posts = [];
  for (const f of files.sort()) {
    const post = parsePost(f, readFileSync(`${root}data/blog/${f}`, "utf8"));
    if (post) posts.push(post);
    else console.warn(`bundle-blog: skipping ${f} (missing/malformed frontmatter)`);
  }
  posts.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

  mkdirSync(`${root}data/generated`, { recursive: true });
  writeFileSync(
    `${root}data/generated/blog.ts`,
    `// Generated by scripts/bundle-blog.mjs — do not edit by hand.
export interface BlogPost {
  slug: string;
  title: string;
  date: string; // ISO YYYY-MM-DD
  body: string; // markdown
}

export const blogPosts: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`,
  );
  console.log(`bundle-blog: ${posts.length} post(s)`);
}

if (process.argv[1]?.endsWith("bundle-blog.mjs")) main();
