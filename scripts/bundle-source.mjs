/**
 * Bundle the curated source files (data/source-manifest.mjs) into a typed
 * module the virtual filesystem imports — visitors browse this site's real
 * code inside the site (FLOW.md §8). Runs on predev/prebuild; the output is
 * committed so tests and fresh checkouts work without a build step.
 */
import { readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { sourceManifest } from "../data/source-manifest.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const out = {};
let totalBytes = 0;
let fileCount = 0;

for (const [slug, files] of Object.entries(sourceManifest)) {
  out[slug] = {};
  for (const rel of files) {
    const abs = join(root, rel);
    const raw = readFileSync(abs, "utf8");
    out[slug][rel] = raw;
    totalBytes += statSync(abs).size;
    fileCount += 1;
  }
}

const banner = `/**
 * GENERATED by scripts/bundle-source.mjs — do not edit.
 * Curate files in data/source-manifest.mjs and run \`npm run bundle-source\`.
 */
`;

const body =
  banner +
  `export const siteSource: Record<string, Record<string, string>> = ` +
  JSON.stringify(out) +
  `;\n\n` +
  `/** Real numbers for the fake BIOS memory check. */\n` +
  `export const bundleInfo = { files: ${fileCount}, bytes: ${totalBytes} };\n`;

mkdirSync(join(root, "data/generated"), { recursive: true });
writeFileSync(join(root, "data/generated/site-source.ts"), body);
console.log(`bundled ${fileCount} files (${(totalBytes / 1024).toFixed(1)} KiB) into data/generated/site-source.ts`);
